# The functionality that all indiedown template packages share:
# the output format that applies the assets in `inst/indiedown`,
# the choice of the main font,
# helpers for writing LaTeX from R,
# and helpers for testing the rendered pages with snapshots.
# `create_indiedown_package()` includes this file in new template packages.
# To update it, run in the template package:
#
#   usethis::use_standalone("cynkra/indiedown", "indiedown")
#
# Do not edit this file in a template package,
# customize the other files of the skeleton instead.
# Where `fc-list` is not available, such as on macOS,
# installed fonts are detected with the systemfonts package if it is installed:
# list it in `Suggests`.
#
# The snapshot helpers `expect_pdf_snapshot()` and `skip_if_no_pdf_snapshot()`
# at the end of the file are for the tests of a template package.
# They are internal, call them from the tests without a prefix.
# They need the packages testthat, pdftools, callr, tinytex, showtext,
# and sysfonts, and png for the `tolerance` argument.
# These are not in `imports:` above, because they are only used in tests:
# list them in the `Suggests:` field of the template package.
# The snapshot helpers are not excluded from coverage in this file,
# because indiedown tests them.
# A template package can exclude the file with a `.covrignore` file.
#
