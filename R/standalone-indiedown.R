# Draws the text of plots with showtext, see "Fonts" above:
# registers the font files in `fonts` as the default font family,
# and sets the chunk option `fig.showtext` until the calling function ends.
# The option is a default of knitr's chunk options, a chunk can override it.
local_showtext <- function(fonts, .local_envir = parent.frame()) {
  files <- plot_font_files(fonts)
  if (!is.null(files)) {
    sysfonts::font_add(
      "",
      files$regular,
      files$bold,
      files$italic,
      files$bolditalic
    )
  }
  options <- knitr::opts_chunk$get()
  withr::defer(knitr::opts_chunk$restore(options), envir = .local_envir)
  knitr::opts_chunk$set(fig.showtext = TRUE)
  invisible()
}

# The paths of the font files of the four faces in a directory,
# or `NULL` if it has no font files.
# A missing face is `NULL`, which sysfonts replaces by the regular face.
plot_font_files <- function(dir) {
  files <- font_files(dir)
  if (length(files) == 0) {
    return(NULL)
  }
  names <- tolower(files)
  bold <- grepl("bold", names)
  italic <- grepl("italic|oblique", names)
  face <- function(is_face, default = NULL) {
    if (any(is_face)) file.path(dir, files[is_face][[1]]) else default
  }
  regular <- face(!bold & !italic, file.path(dir, files[[1]]))
  list(
    regular = regular,
    bold = face(bold & !italic),
    italic = face(italic & !bold),
    bolditalic = face(bold & italic)
  )
}

# The file names of the page snapshots of `name`
# in the snapshot directory of the current test file,
# or `NULL` outside of a test run.
# testthat exports no function for that directory:
# it is read from testthat's internal snapshot reporter,
# and an error says so if that is not possible,
# rather than silently skipping the check of the page count.
pdf_snapshot_pages <- function(name) {
  if (!testthat::is_testing()) {
    return(NULL)
  }
  snapshotter <- getOption("testthat.snapshotter")
  if (
    !rlang::is_string(snapshotter$snap_dir) ||
      !rlang::is_string(snapshotter$file)
  ) {
    rlang::abort(c(
      "Can't find the snapshot directory of the current test file.",
      i = paste(
        "The page count of a PDF snapshot is checked",
        "with internals of testthat, which may have changed."
      )
    ))
  }
  files <- dir(file.path(snapshotter$snap_dir, snapshotter$file))
  prefix <- paste0(name, "-")
  rest <- substring(files, nchar(prefix) + 1)
  files[startsWith(files, prefix) & grepl("^page-[0-9]+[.]png$", rest)]
}

announce_pdf_snapshot <- function(name) {
  if (!testthat::is_testing()) {
    return(invisible())
  }
  files <- unique(basename(list.files(
    testthat::test_path("_snaps"),
    recursive = TRUE
  )))
  prefix <- paste0(name, "-")
  rest <- substring(files, nchar(prefix) + 1)
  ours <- startsWith(files, prefix) &
    grepl("^(page-[0-9]+[.]png|environment[.]txt)$", rest)
  for (file in files[ours]) {
    testthat::announce_snapshot_file(file)
  }
  invisible()
}

font_files <- function(dir) {
  if (is.null(dir) || !dir.exists(dir)) {
    return(character())
  }
  files <- list.files(
    dir,
    pattern = "[.](otf|ttf|ttc|pfa|pfb)$",
    ignore.case = TRUE,
    recursive = TRUE
  )
  sort(files, method = "radix")
}

# The fallback is only added if the template bundles no fonts:
# next to the bundled fonts, fontconfig would offer it for some styles
# and mix two families in one plot.
visible_fonts <- function(fonts, dir) {
  if (length(font_files(fonts)) > 0) {
    return(fonts)
  }

  files <- paste0(
    "lmsans10-",
    c("regular", "bold", "oblique", "boldoblique"),
    ".otf"
  )
  paths <- run_command("kpsewhich", files)
  if (length(paths) != length(files)) {
    rlang::abort(c(
      "Can't find the fallback font Latin Modern Sans with `kpsewhich`.",
      i = paste(
        "Bundle fonts with the template in `inst/indiedown/fonts`,",
        "or set `system_fonts = TRUE`."
      )
    ))
  }

  fallback <- file.path(dir, "fonts-fallback")
  dir.create(fallback)
  file.copy(paths, fallback)
  fallback
}

write_fonts_conf <- function(fonts, dir) {
  conf <- file.path(dir, "fonts.conf")
  writeLines(
    c(
      "<?xml version=\"1.0\"?>",
      "<!DOCTYPE fontconfig SYSTEM \"fonts.dtd\">",
      "<fontconfig>",
      paste0("  <dir>", xml_escape(fonts), "</dir>"),
      paste0(
        "  <cachedir>",
        xml_escape(file.path(dir, "fontconfig-cache")),
        "</cachedir>"
      ),
      "</fontconfig>"
    ),
    conf
  )
  conf
}

xml_escape <- function(x) {
  x <- gsub("&", "&amp;", x, fixed = TRUE)
  x <- gsub("<", "&lt;", x, fixed = TRUE)
  gsub(">", "&gt;", x, fixed = TRUE)
}

# Returns the file names of the pages, in the directory of `pdf`.
rasterize_pdf <- function(pdf, name, dpi) {
  # `filenames` is a format for sprintf(): page number and file extension
  prefix <- gsub("%", "%%", file.path(dirname(pdf), name), fixed = TRUE)
  pages <- callr::r(
    convert_pdf,
    args = list(pdf, paste0(prefix, "-page-%02d.%s"), dpi)
  )
  basename(pages)
}

# This function runs in a separate R process.
# Its environment is the global environment there,
# so it can only use other packages.
convert_pdf <- function(pdf, filenames, dpi) {
  pdftools::pdf_convert(
    pdf,
    format = "png",
    filenames = filenames,
    dpi = dpi,
    verbose = FALSE
  )
}

compare_png <- function(tolerance) {
  force(tolerance)
  function(old, new) {
    if (testthat::compare_file_binary(old, new)) {
      return(TRUE)
    }
    if (tolerance == 0) {
      return(FALSE)
    }
    old <- png::readPNG(old)
    new <- png::readPNG(new)
    if (!identical(dim(old), dim(new))) {
      return(FALSE)
    }
    differs <- old != new
    if (length(dim(differs)) == 3) {
      differs <- rowSums(differs, dims = 2) > 0
    }
    mean(differs) <= tolerance
  }
}

