# Snapshots of rendered PDF documents ------------------------------------------

# `expect_pdf_snapshot(name, rmd, ..., tolerance, dpi, system_fonts, fonts)`
# renders an R Markdown document to PDF,
# rasterizes each page to PNG with poppler via the pdftools package,
# and compares each page with its snapshot
# using `testthat::expect_snapshot_file()`.
# Use it in the tests of a template package
# to catch unintended changes to the rendered pages,
# such as fonts, margins, title pages, or the placement of floats.
#
# `skip_if_no_pdf_snapshot()` skips the current test
# where PDF snapshots cannot be taken:
# on CRAN, on systems other than Linux,
# and without rmarkdown, pdftools, callr, showtext, sysfonts, pandoc, or LaTeX.
# `expect_pdf_snapshot()` calls it before rendering.
#
# Arguments:
# * `name`: Prefix of the snapshot file names, unique within a test file.
# * `rmd`: The lines of the R Markdown document, a character vector.
#   It is rendered in a temporary directory,
#   in a new environment whose parent is the global environment.
# * `...`: These dots are for future extensions and must be empty.
# * `tolerance`: The share of pixels, between 0 and 1,
#   that may differ between a page and its snapshot.
#   The default, 0, requires the PNG files to be byte-identical.
#   A positive value needs the png package.
# * `dpi`: Resolution of the rasterized pages, in dots per inch.
# * `system_fonts`: If `FALSE`, the default,
#   fontconfig sees only the fonts in `fonts`, or the fallback.
#   If `TRUE`, it sees the fonts installed on the system.
# * `fonts`: Directory with the fonts that the template bundles.
#   The default, `NULL`, uses `inst/indiedown/fonts` of the template package.
#
# `expect_pdf_snapshot()` returns `NULL`, invisibly.
# `skip_if_no_pdf_snapshot()` returns `TRUE`, invisibly, if it does not skip.
#
# ## Snapshot files
#
# For `name = "report"`, the snapshot directory of the test file holds
# `report-page-01.png`, `report-page-02.png`, and so on, one for each page,
# and `report-environment.txt`, a record of the toolchain.
# The record lists the versions of the operating system, R, pandoc, LaTeX,
# poppler, fontconfig, FreeType, and the R packages involved,
# the font that fontconfig offers for Helvetica,
# and a hash of each font file that the template bundles,
# or of the fallback fonts.
# The record never fails a test:
# it is written when the snapshot is created and kept as is afterwards.
# To refresh the snapshots and the record,
# delete the snapshot files of `name` and run the tests again.
#
# If the document has more or fewer pages than there are page snapshots,
# the test fails, and only the pages that have a snapshot are compared.
# The page snapshots are looked up in the snapshot directory of the test file
# that testthat uses while it runs the tests,
# and an error is thrown if that directory cannot be determined.
# To accept a new page count, delete the snapshot files of `name`.
#
# Pixel-exact comparisons are only stable on a fixed toolchain,
# so `skip_if_no_pdf_snapshot()` skips on systems other than Linux.
# A positive `tolerance` accepts small differences.
#
# testthat deletes the snapshot files that a complete test run does not use.
# When it skips or when rendering fails,
# `expect_pdf_snapshot()` declares the existing snapshot files of `name`
# with `testthat::announce_snapshot_file()`,
# so that a test run on a system without LaTeX keeps them.
#
# ## Fonts
#
# R's `grDevices::pdf()` device, the default device of the knitr chunks,
# does not embed the fonts of a plot, it refers to a standard font by name.
# poppler substitutes the font that fontconfig offers for that name,
# so the rasterized plot text would depend on the fonts of the system.
# `expect_pdf_snapshot()` therefore sets the chunk option `fig.showtext = TRUE`
# while it renders the document, and only then,
# so that the showtext package draws the text of plots as outlines.
# It registers the font files that the template bundles in `fonts`
# with `sysfonts::font_add()` as the font family `""`,
# the family that base graphics and ggplot2 use by default,
# for example with `base_family = ""`.
# The font files are matched to the regular, bold, italic,
# and bold italic face by the words `bold`, `italic`, and `oblique`
# in their names.
# Plot text that names another family, such as `sans`,
# is drawn with the default font of the sysfonts package.
# The registration lasts for the R session, it is not undone.
# The template itself sets no graphics device and no plot font:
# the fonts of plots in regular documents are up to their authors.
#
# The text of the document is set by LaTeX,
# which finds the main font through fontconfig.
# Unless `system_fonts = TRUE`,
# `expect_pdf_snapshot()` lets fontconfig see
# only the fonts that the template bundles in `fonts`
# while the document is rendered and rasterized,
# so that a font installed on the system does not replace the bundled one.
# If the template bundles no fonts,
# Latin Modern Sans from the LaTeX installation is the fixed fallback.
# The pages are rasterized in a separate R process,
# because fontconfig reads its configuration only once per process.
#
# ## Example
#
# In `tests/testthat/test-visual.R` of a template package called mydown:
#
#   test_that("the report looks right", {
#     expect_pdf_snapshot(
#       "report",
#       c(
#         "---",
#         "title: Report",
#         "date: January 1, 2026",
#         "output: mydown::mydown",
#         "---",
#         "",
#         "Some text."
#       )
#     )
#   })
expect_pdf_snapshot <- function(
  name,
  rmd,
  ...,
  tolerance = 0,
  dpi = 100,
  system_fonts = FALSE,
  fonts = NULL
) {
  rlang::check_dots_empty()
  check_pdf_snapshot_args(name, rmd, tolerance, dpi, system_fonts, fonts)

  # Unless the snapshots are taken, declare the existing ones,
  # so that a complete test run does not delete them as unused.
  taken <- FALSE
  withr::defer(if (!taken) announce_pdf_snapshot(name))

  skip_if_no_pdf_snapshot()
  if (tolerance > 0) {
    rlang::check_installed("png", "to compare PDF snapshots with a tolerance.")
  }

  dir <- withr::local_tempdir()
  if (is.null(fonts)) {
    fonts <- indiedown_path("fonts")
  }
  if (!system_fonts) {
    fonts <- visible_fonts(fonts, dir)
    withr::local_envvar(FONTCONFIG_FILE = write_fonts_conf(fonts, dir))
  }

  input <- file.path(dir, paste0(name, ".Rmd"))
  writeLines(rmd, input)
  local_showtext(fonts)
  pdf <- rmarkdown::render(
    input,
    output_dir = dir,
    quiet = TRUE,
    envir = new.env(parent = globalenv())
  )

  pages <- rasterize_pdf(pdf, name, dpi)
  record <- paste0(name, "-environment.txt")
  writeLines(
    pdf_snapshot_environment(pdf, fonts, system_fonts),
    file.path(dir, record)
  )

  # A change of the page count fails, see "Snapshot files" above
  snaps <- pdf_snapshot_pages(name)
  same_count <- length(snaps) %in% c(0, length(pages))

  # Injecting the file name gives a readable label in failure messages
  compare <- compare_png(tolerance)
  for (page in pages[same_count | pages %in% snaps]) {
    rlang::inject(testthat::expect_snapshot_file(
      file.path(dir, !!page),
      compare = compare
    ))
  }
  rlang::inject(testthat::expect_snapshot_file(
    file.path(dir, !!record),
    compare = compare_true
  ))

  if (!same_count) {
    testthat::fail(sprintf(
      paste(
        "The page count of `%s` changed: %d rendered, %d in the snapshot.",
        "To accept the change, delete the snapshot files of `%s`",
        "and run the tests again."
      ),
      name,
      length(pages),
      length(snaps),
      name
    ))
  }

  # After a failure, the existing snapshot files are kept
  taken <- same_count
  invisible()
}

skip_if_no_pdf_snapshot <- function() {
  testthat::skip_on_cran()
  if (!is_linux()) {
    testthat::skip("PDF snapshots are pixel-exact on Linux only")
  }
  testthat::skip_if_not_installed("rmarkdown")
  testthat::skip_if_not_installed("pdftools")
  testthat::skip_if_not_installed("callr")
  testthat::skip_if_not_installed("showtext")
  testthat::skip_if_not_installed("sysfonts")
  testthat::skip_if_not(
    rmarkdown::pandoc_available(),
    "pandoc is not available"
  )
  testthat::skip_if_not(has_latex(), "LaTeX is not available")
  invisible(TRUE)
}

check_pdf_snapshot_args <- function(
  name,
  rmd,
  tolerance,
  dpi,
  system_fonts,
  fonts,
  call = rlang::caller_env()
) {
  if (!rlang::is_string(name) || !nzchar(name)) {
    rlang::abort("`name` must be a non-empty string.", call = call)
  }
  if (!is.character(rmd)) {
    rlang::abort("`rmd` must be a character vector.", call = call)
  }
  if (!is_number(tolerance) || tolerance < 0 || tolerance > 1) {
    rlang::abort("`tolerance` must be a number between 0 and 1.", call = call)
  }
  if (!is_number(dpi) || dpi <= 0) {
    rlang::abort("`dpi` must be a positive number.", call = call)
  }
  if (!rlang::is_bool(system_fonts)) {
    rlang::abort("`system_fonts` must be `TRUE` or `FALSE`.", call = call)
  }
  if (!is.null(fonts) && !(rlang::is_string(fonts) && dir.exists(fonts))) {
    rlang::abort(
      "`fonts` must be the path to a directory or `NULL`.",
      call = call
    )
  }
}

