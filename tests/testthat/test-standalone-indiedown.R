# The skeleton carries R/standalone-indiedown.R
# as usethis::use_standalone() writes it into a template package.

skeleton_copy <- function() {
  system.file(
    "mypackage",
    "R",
    "import-standalone-indiedown.R",
    package = "indiedown"
  )
}

test_that("the skeleton's copy of the standalone file is up to date", {
  # R/ is only available in the source tree, not under R CMD check
  canonical <- test_path("..", "..", "R", "standalone-indiedown.R")
  skip_if_not(file.exists(canonical), "R/standalone-indiedown.R not found")

  expect_identical(
    readLines(skeleton_copy()),
    c(
      "# Standalone file: do not edit by hand",
      "# Source: https://github.com/cynkra/indiedown/blob/HEAD/R/standalone-indiedown.R",
      '# Generated by: usethis::use_standalone("cynkra/indiedown", "indiedown")',
      paste0("# ", strrep("-", 70)),
      "#",
      readLines(canonical)
    )
  )
})

test_that("the skeleton's copy of the standalone file defines indiedown's functions", {
  # covr instruments the functions in the namespace
  skip_on_covr()

  copy <- new.env()
  sys.source(skeleton_copy(), envir = copy, keep.source = FALSE)
  names <- ls(copy, all.names = TRUE)
  ns <- asNamespace("indiedown")

  # the file also defines an environment, which deparses as "<environment>"
  strip <- function(f) {
    if (is.function(f)) {
      f <- utils::removeSource(f)
    }
    deparse(f)
  }
  expect_identical(
    lapply(mget(names, envir = copy), strip),
    lapply(mget(names, envir = ns, inherits = FALSE), strip)
  )
})
